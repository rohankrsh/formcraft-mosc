/**
 * Runs all pending migrations in deterministic order.
 */
export async function runMigrations() {
  let health = await getOracleHealth();
  if (!health.connected) {
    const { initOraclePool } = await import('./oracle.js');
    await initOraclePool();
    health = await getOracleHealth();
  }
  if (!health.connected) {
    console.warn('[Migration] Cannot run migrations: Oracle Database connection is not available.');
    return { success: false, reason: 'database_unavailable' };
  }

  let result = { success: true, applied: [] };

  await withTransaction(async (conn) => {
    await ensureMigrationTable(conn);

    const checkSql = "SELECT MIGRATION_ID FROM FORMCRAFT_SCHEMA_MIGRATIONS";
    const res = await conn.execute(checkSql);
    const appliedSet = new Set((res.rows || []).map(r => r.MIGRATION_ID || r.migration_id));

    // Migration 001
    if (!appliedSet.has(MIGRATION_001_ID)) {
      await applyMigration001(conn);
      result.applied.push(MIGRATION_001_ID);
    } else {
      console.log(`[Migration] ${MIGRATION_001_ID} is already applied.`);
    }

    // Migration 002
    if (!appliedSet.has(MIGRATION_002_ID)) {
      await applyMigration002(conn);
      result.applied.push(MIGRATION_002_ID);
    } else {
      console.log(`[Migration] ${MIGRATION_002_ID} is already applied.`);
    }
  });

  return result;
}

// Allow direct execution from CLI: node server/database/migrationRunner.js
if (process.argv[1] && process.argv[1].endsWith('migrationRunner.js')) {
  import('./oracle.js').then(async ({ initOraclePool, closeOraclePool }) => {
    try {
      await initOraclePool();
      const res = await runMigrations();
      console.log('[Migration] Migration process complete:', res);
    } catch (err) {
      console.error('[Migration] Failed:', err);
      process.exit(1);
    } finally {
      await closeOraclePool();
    }
  });
}
