import 'dotenv/config';
import { executeQuery, withTransaction, getOracleHealth } from './oracle.js';

/**
 * Migration 001: Core FormCraft Oracle-First Persistence Schema
 */
const MIGRATION_001_ID = '001_create_formcraft_schema';
const MIGRATION_001_DESC = 'Initializes FORMCRAFT_FORMS, DRAFTS, VERSIONS, DEPARTMENTS, and SERVICE_CENTERS';

async function tableExists(conn, tableName) {
  const sql = "SELECT COUNT(*) AS CNT FROM USER_TABLES WHERE TABLE_NAME = :tbl";
  const res = await conn.execute(sql, { tbl: tableName.toUpperCase() });
  return (res.rows && res.rows[0] && (res.rows[0].CNT || res.rows[0].cnt) > 0);
}

async function indexExists(conn, indexName) {
  const sql = "SELECT COUNT(*) AS CNT FROM USER_INDEXES WHERE INDEX_NAME = :idx";
  const res = await conn.execute(sql, { idx: indexName.toUpperCase() });
  return (res.rows && res.rows[0] && (res.rows[0].CNT || res.rows[0].cnt) > 0);
}

/**
 * Ensures migration tracking table exists
 */
async function ensureMigrationTable(conn) {
  const exists = await tableExists(conn, 'FORMCRAFT_SCHEMA_MIGRATIONS');
  if (!exists) {
    console.log('[Migration] Creating FORMCRAFT_SCHEMA_MIGRATIONS table...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_SCHEMA_MIGRATIONS (
        MIGRATION_ID VARCHAR2(100) PRIMARY KEY,
        APPLIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        DESCRIPTION VARCHAR2(255)
      )
    `);
    console.log('[Migration] FORMCRAFT_SCHEMA_MIGRATIONS created successfully.');
  }
}

/**
 * Applies Migration 001
 */
async function applyMigration001(conn) {
  console.log(`[Migration] Applying ${MIGRATION_001_ID}...`);

  // 1. FORMCRAFT_FORMS
  if (!(await tableExists(conn, 'FORMCRAFT_FORMS'))) {
    console.log('[Migration] Creating FORMCRAFT_FORMS...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_FORMS (
        ID VARCHAR2(100) PRIMARY KEY,
        NAME VARCHAR2(255) NOT NULL,
        SLUG VARCHAR2(255) UNIQUE NOT NULL,
        DESCRIPTION VARCHAR2(1000),
        STATUS VARCHAR2(50) DEFAULT 'draft' NOT NULL,
        CURRENT_DRAFT_REVISION NUMBER DEFAULT 1 NOT NULL,
        PUBLISHED_VERSION NUMBER,
        PRIMARY_ENTITY VARCHAR2(100),
        CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CREATED_BY VARCHAR2(100),
        UPDATED_BY VARCHAR2(100)
      )
    `);
  }

  // 2. FORMCRAFT_FORM_DRAFTS
  if (!(await tableExists(conn, 'FORMCRAFT_FORM_DRAFTS'))) {
    console.log('[Migration] Creating FORMCRAFT_FORM_DRAFTS...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_FORM_DRAFTS (
        FORM_ID VARCHAR2(100) PRIMARY KEY,
        REVISION_NUMBER NUMBER DEFAULT 1 NOT NULL,
        DEFINITION_JSON CLOB NOT NULL,
        UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_BY VARCHAR2(100),
        CONSTRAINT FK_FC_DRAFT_FORM FOREIGN KEY (FORM_ID) 
          REFERENCES FORMCRAFT_FORMS(ID) ON DELETE CASCADE
      )
    `);
  }

  // 3. FORMCRAFT_FORM_VERSIONS
  if (!(await tableExists(conn, 'FORMCRAFT_FORM_VERSIONS'))) {
    console.log('[Migration] Creating FORMCRAFT_FORM_VERSIONS...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_FORM_VERSIONS (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        FORM_ID VARCHAR2(100) NOT NULL,
        VERSION_NUMBER NUMBER NOT NULL,
        DEFINITION_JSON CLOB NOT NULL,
        PUBLISHED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        PUBLISHED_BY VARCHAR2(100),
        CHANGE_SUMMARY VARCHAR2(1000),
        CONSTRAINT UQ_FC_FORM_VER UNIQUE (FORM_ID, VERSION_NUMBER),
        CONSTRAINT FK_FC_VER_FORM FOREIGN KEY (FORM_ID) 
          REFERENCES FORMCRAFT_FORMS(ID) ON DELETE CASCADE
      )
    `);
  }

  // 4. FORMCRAFT_FORM_DEPARTMENTS
  if (!(await tableExists(conn, 'FORMCRAFT_FORM_DEPARTMENTS'))) {
    console.log('[Migration] Creating FORMCRAFT_FORM_DEPARTMENTS...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_FORM_DEPARTMENTS (
        FORM_ID VARCHAR2(100) NOT NULL,
        DEPARTMENT_ID VARCHAR2(100) NOT NULL,
        DEPARTMENT_NAME VARCHAR2(255),
        ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_FC_FORM_DEPT PRIMARY KEY (FORM_ID, DEPARTMENT_ID),
        CONSTRAINT FK_FC_DEPT_FORM FOREIGN KEY (FORM_ID) 
          REFERENCES FORMCRAFT_FORMS(ID) ON DELETE CASCADE
      )
    `);
  }

  // 5. FORMCRAFT_FORM_SERVICE_CENTERS
  if (!(await tableExists(conn, 'FORMCRAFT_FORM_SERVICE_CENTERS'))) {
    console.log('[Migration] Creating FORMCRAFT_FORM_SERVICE_CENTERS...');
    await conn.execute(`
      CREATE TABLE FORMCRAFT_FORM_SERVICE_CENTERS (
        FORM_ID VARCHAR2(100) NOT NULL,
        SERVICE_CENTER_ID VARCHAR2(100) NOT NULL,
        SERVICE_CENTER_NAME VARCHAR2(255),
        ASSIGNED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_FC_FORM_SVC PRIMARY KEY (FORM_ID, SERVICE_CENTER_ID),
        CONSTRAINT FK_FC_SVC_FORM FOREIGN KEY (FORM_ID) 
          REFERENCES FORMCRAFT_FORMS(ID) ON DELETE CASCADE
      )
    `);
  }

  // 6. Helpful Indexes
  if (!(await indexExists(conn, 'IDX_FC_FORMS_STATUS'))) {
    try {
      await conn.execute(`CREATE INDEX IDX_FC_FORMS_STATUS ON FORMCRAFT_FORMS (STATUS)`);
    } catch (e) {
      if (e.errorNum !== 1408 && e.errorNum !== 955) throw e;
    }
  }
  if (!(await indexExists(conn, 'IDX_FC_SUB_FORM_VER'))) {
    try {
      await conn.execute(`CREATE INDEX IDX_FC_SUB_FORM_VER ON FORMCRAFT_SUBMISSIONS (FORM_ID, FORM_VERSION)`);
    } catch (e) {
      if (e.errorNum !== 1408 && e.errorNum !== 955) throw e;
    }
  }

  // Record migration as applied
  await conn.execute(`
    INSERT INTO FORMCRAFT_SCHEMA_MIGRATIONS (MIGRATION_ID, DESCRIPTION)
    VALUES (:b_id, :b_desc)
  `, { b_id: MIGRATION_001_ID, b_desc: MIGRATION_001_DESC });

  console.log(`[Migration] ${MIGRATION_001_ID} applied successfully.`);
}

